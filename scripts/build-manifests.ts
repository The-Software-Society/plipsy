/**
 * Walk assets/audio and assets/illustrations and emit the typed manifest
 * modules so the Metro bundler can require() them.
 */

import { readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = process.cwd();

const walk = (dir: string): string[] => {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
};

const buildAudioManifest = () => {
  const dir = join(ROOT, 'assets', 'audio');
  const files = walk(dir).filter((f) => /\.(mp3|wav|m4a)$/.test(f));

  const entries: string[] = [];
  let chimeRequire: string | null = null;
  let pageTurnRequire: string | null = null;

  for (const file of files) {
    const rel = relative(ROOT, file).split(sep).join('/');
    const filename = file.split(sep).pop()!.replace(/\.(mp3|wav|m4a)$/, '');

    if (filename === 'sfx.chime') {
      chimeRequire = `require('@/${rel}')`;
      continue;
    }
    if (filename === 'sfx.page-turn') {
      pageTurnRequire = `require('@/${rel}')`;
      continue;
    }

    const key = filename;
    entries.push(`  '${key}': require('@/${rel}'),`);
  }

  const out = [
    '// Auto-generated by `npm run generate:manifests`. Do not edit by hand.',
    '',
    'export const audioManifest: Record<string, number> = {',
    ...entries.sort(),
    '};',
    '',
    'export const sfxManifest = {',
    `  chime: ${chimeRequire ?? 'null as number | null'},`,
    `  pageTurn: ${pageTurnRequire ?? 'null as number | null'},`,
    '};',
    '',
    'export const hasAudio = (key: string): boolean => key in audioManifest;',
    '',
  ].join('\n');

  writeFileSync(join(ROOT, 'src', 'audio', 'manifest.ts'), out);
  console.log(`audio: ${entries.length} files`);
};

const buildIllustrationManifest = () => {
  const dir = join(ROOT, 'assets', 'illustrations');
  const files = walk(dir).filter((f) => /\.(png|jpg|jpeg|webp)$/.test(f));

  const entries: string[] = [];
  for (const file of files) {
    const rel = relative(ROOT, file).split(sep).join('/');
    // path shape: assets/illustrations/<group>/<name>.png
    const parts = rel.split('/');
    const group = parts[2];
    const name = parts[3]!.replace(/\.(png|jpg|jpeg|webp)$/, '');
    const key = `${group}.${name}`;
    entries.push(`  '${key}': require('@/${rel}'),`);
  }

  const out = [
    '// Auto-generated by `npm run generate:manifests`. Do not edit by hand.',
    '',
    "import { ImageRequireSource } from 'react-native';",
    '',
    'export const illustrationManifest: Record<string, ImageRequireSource> = {',
    ...entries.sort(),
    '};',
    '',
    'export const hasIllustration = (key: string): boolean => key in illustrationManifest;',
    '',
  ].join('\n');

  writeFileSync(join(ROOT, 'src', 'stories', 'illustration-manifest.ts'), out);
  console.log(`illustrations: ${entries.length} files`);
};

buildAudioManifest();
buildIllustrationManifest();
